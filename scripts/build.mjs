import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFile(path.join(root,'src',name),'utf8');
const [shell,css,assetCss,themeCss,ledgerCss,theme,core,storage,importer,ledger,ledgerImporter,app]=await Promise.all(['shell.html','styles.css','assets.css','themes.css','ledger.css','theme.mjs','portfolio.mjs','storage.mjs','json-import.mjs','ledger.mjs','ledger-import.mjs','ui.js'].map(read));
const inline=text=>text.replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');
const source='(async()=>{\n'+[core,storage,importer,ledger,ledgerImporter,app].map(inline).join('\n')+'\n})().catch(error=>{document.getElementById("kapital-app").textContent="Не удалось открыть приложение: "+error.message;});';
const bootstrap='(()=>{'+inline(theme)+'\nwindow.kapitalTheme=createThemeController(window);})();';
const html=shell.replace('/* THEME_BOOTSTRAP */',()=>bootstrap.replace(/<\/script/gi,'<\\/script')).replace('/* STYLES */',()=>css+'\n'+assetCss+'\n'+themeCss+'\n'+ledgerCss).replace('/* APPLICATION */',()=>source.replace(/<\/script/gi,'<\\/script'));
const {version}=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
const sw=await read('sw.js');
const build=createHash('sha256').update(version).update(html).update(sw).digest('hex').slice(0,12);
const stamp=text=>text.replaceAll('__APP_VERSION__',()=>version).replaceAll('__VERSION__',()=>build);
const page=stamp(html);
await fs.mkdir(path.join(root,'dist'),{recursive:true});await fs.writeFile(path.join(root,'dist','index.html'),page);
await fs.writeFile(path.join(root,'dist','Kapital.html'),page);
await fs.writeFile(path.join(root,'dist','sw.js'),stamp(sw));
console.log('Built standalone HTML '+version+' ('+Buffer.byteLength(page)+' bytes), cache '+build);
